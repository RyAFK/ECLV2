const TIMELINE_STAGES = [
  "Referral received",
  "Patient contacted",
  "Clinical triage completed",
  "Consultation booked",
  "Consultant assessment completed",
  "Treatment recommendation recorded",
  "Treatment booked",
  "Procedure completed",
  "Postoperative follow-up",
  "Returned to referrer / pathway completed",
];

function buildTimeline(
  notesByStage: Record<number, { date: string; note: string; staffInitials?: string }>,
  reachedIndex: number
): PathwayTimelineStep[] {
  return TIMELINE_STAGES.map((stage, index) => {
    const entry = notesByStage[index];
    return {
      stage,
      complete: index <= reachedIndex,
      date: entry?.date,
      note: entry?.note,
      staffInitials: entry?.staffInitials,
    };
  });
}

